/** Ταυτότητα μιας καταχώρησης για την ένδειξη «νέο» (version αν υπάρχει,
 * αλλιώς η ημερομηνία). Συγκρίνεται αλφαβητικά με το αποθηκευμένο «είδα»
 * (ένα APP_BUILD_VERSION), π.χ. "2026-10-08.20" < "2026-10-09" < "2026-10-09.11". */
export function changelogKey(entry) {
  return entry.version ?? entry.date;
}

/** Οι καταχωρήσεις που βλέπει ο χρήστης: ο διαχειριστής όλες, ο επισκέπτης
 * μόνο τις γραμμές "all", χωρίς τις καταχωρήσεις που έμειναν κενές. */
export function changelogFor(isAdmin) {
  return CHANGELOG.map((entry) => ({
    ...entry,
    items: entry.items.filter((it) => isAdmin || it.audience === "all"),
  })).filter((entry) => entry.items.length > 0);
}

const GREEK_MONTHS_GENITIVE = [
  "Ιανουαρίου", "Φεβρουαρίου", "Μαρτίου", "Απριλίου", "Μαΐου", "Ιουνίου",
  "Ιουλίου", "Αυγούστου", "Σεπτεμβρίου", "Οκτωβρίου", "Νοεμβρίου", "Δεκεμβρίου",
];

/** "2026-10-09" -> "9 Οκτωβρίου 2026". */
export function formatChangelogDate(ymd) {
  const [y, m, d] = String(ymd || "").split("-").map(Number);
  if (!y || !m || !d) return ymd || "";
  return `${d} ${GREEK_MONTHS_GENITIVE[m - 1]} ${y}`;
}
